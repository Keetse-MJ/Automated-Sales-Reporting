#9. Create a stored procedure that accepts a salesperson's name and returns their sales ordered from highest amount to lowest amount.
#Return: sale_id, product ,amount ,sale_date

DELIMITER $$
CREATE PROCEDURE sales_ordering(p_salesperson VARCHAR(50))
BEGIN
SELECT sale_id,product,amount,sale_date
FROM sales
WHERE salesperson = p_salesperson
ORDER BY amount DESC;
END $$

CALL sales_ordering ("Thabo");


#10. The manager wants a procedure that accepts a salesperson's name and returns a summary of their performance.
# Return:salesperson,total sales ,average sale amount ,number of sales,highest individual sale


DELIMITER $$
CREATE PROCEDURE salesperson_performance (p_salesperson VARCHAR(50))
BEGIN
SELECT salesperson,SUM(amount) total_sales,AVG(amount)average_sale_amount,COUNT(*) number_of_sales,MAX(amount) highest_sale
FROM sales
WHERE salesperson =p_salesperson
GROUP BY salesperson;
END $$

CALL salesperson_performance("Lerato");
















