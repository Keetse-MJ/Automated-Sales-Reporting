#8. The manager wants to find the highest individual sale made by a particular salesperson.
# Create a stored procedure that accepts a salesperson's name and returns: salesperson ,highest sale

DELIMITER $$
CREATE PROCEDURE highest_sale(IN p_salesperson VARCHAR(50))
